/**
 * AegisPay Domain Layer & Audit State Machine
 *
 * Core defensive financial architecture:
 * 1. Decoupled status enums: Verification, Policy, and Payout lifecycles operate independently.
 * 2. Integer minor units: Prevents floating-point math inaccuracies across transactions.
 * 3. Immutable deliverable manifests: Cryptographically references Git commit SHA to prevent TOCTOU.
 * 4. Deterministic payout tracking: Strict idempotency and challenge window support.
 * 5. Asynchronous Webhook Telemetry: Full lifecycle tracking for PayPal batch and item states.
 */

// ---------------------------------------------------------------------------
// 1. Decoupled Status Types
// ---------------------------------------------------------------------------

/**
 * Status of deliverable and artifact automated verification (static analysis, test runners).
 */
export type VerificationStatus =
  | 'NOT_STARTED'
  | 'ANALYZING'
  | 'PASSED'
  | 'FAILED'
  | 'STALE';

/**
 * Deterministic business policy status controlling authorization boundaries.
 */
export type PolicyStatus =
  | 'NOT_EVALUATED'
  | 'AUTONOMOUS_APPROVED'
  | 'REQUIRES_HUMAN_SIGN_OFF'
  | 'REJECTED';

/**
 * Payout processing lifecycle directly mapping to PayPal payout states and cooling windows.
 */
export type PayoutStatus =
  | 'NOT_CREATED'
  | 'CHALLENGE_COOLING'
  | 'QUEUED'
  | 'SUBMITTED'
  | 'PROCESSING'
  | 'SUCCESS'
  | 'FAILED'
  | 'UNKNOWN'
  | 'HALTED';

// ---------------------------------------------------------------------------
// 2. Strict Financial Representation
// ---------------------------------------------------------------------------

/**
 * Money representation strictly using integer minor units (cents).
 * e.g., $200.00 is stored as 20000.
 */
export interface Money {
  amountMinor: number;
  currency: 'USD';
}

// ---------------------------------------------------------------------------
// 3. Immutable Deliverable Manifest
// ---------------------------------------------------------------------------

/**
 * Cryptographic snapshot of the submitted deliverable to prevent Time-Of-Check to Time-Of-Use (TOCTOU) exploits.
 */
export interface SubmissionManifest {
  repoUrl: string;
  commitSha: string; // Immutable Git commit hash (fixes TOCTOU)
  treeSha: string;
  diffSummary: string;
  testArtifactHash: string;
  submittedAt: string;
}

// ---------------------------------------------------------------------------
// 4. AI Release Assessment (Advisory Only)
// ---------------------------------------------------------------------------

/**
 * Advisory evaluation generated by the AI reasoning agent.
 * Note: Never carries direct write or fund release authority; pure decision support.
 */
export interface ReleaseAssessment {
  evaluationId: string;
  submissionCommitSha: string;
  sowVersionHash: string;
  confidenceScore: number; // 0-100
  deterministicChecksPassed: boolean;
  securityChecksPassed: boolean;
  reasoning: string;
  detectedRisks: string[];
  evaluatedAt: string;
}

// ---------------------------------------------------------------------------
// 5. Payout Operation & Tracking
// ---------------------------------------------------------------------------

/**
 * Tracked payout operation record with deterministic batch hashing for strict idempotency.
 */
export interface PayoutOperation {
  id: string;
  releaseAuthorizationId: string;
  senderBatchId: string; // Deterministic hash: sha256(contractId:milestoneId:releaseId)
  paypalPayoutBatchId?: string;
  paypalTransactionId?: string;
  amountMinor: number;
  recipientEmail: string;
  status: PayoutStatus;
  errorMessage?: string;
  createdAt: string;
  completedAt?: string;
}

// ---------------------------------------------------------------------------
// 6. PayPal Webhook Telemetry
// ---------------------------------------------------------------------------

export type PayPalWebhookEventType =
  | 'PAYMENT.PAYOUTSBATCH.SUBMITTED'
  | 'PAYMENT.PAYOUTSBATCH.PROCESSING'
  | 'PAYMENT.PAYOUTSBATCH.SUCCESS'
  | 'PAYMENT.PAYOUTS-ITEM.SUCCEEDED'
  | 'PAYMENT.PAYOUTS-ITEM.FAILED';

export interface PayPalTelemetryEvent {
  id: string;
  milestoneId: string;
  eventType: PayPalWebhookEventType;
  timestamp: string;
  summary: string;
  rawPayload: Record<string, any>;
}

// ---------------------------------------------------------------------------
// 7. Root Milestone Entity
// ---------------------------------------------------------------------------

/**
 * Root domain entity representing a contractual escrow milestone.
 */
export interface Milestone {
  id: string;
  contractId: string;
  title: string;
  description: string;
  money: Money;
  contractorEmail: string;
  clientEmail: string;
  acceptanceCriteria: string[];
  sowVersionHash: string;
  maxAutonomousLimitMinor: number; // e.g. 20000 ($200 limit)
  challengeWindowSeconds: number; // e.g. 60s for demo, 7200s for prod
  challengeEndsAt?: string;
  submission?: SubmissionManifest;
  assessment?: ReleaseAssessment;
  payout?: PayoutOperation;
  verificationStatus: VerificationStatus;
  policyStatus: PolicyStatus;
  payoutStatus: PayoutStatus;
  telemetry?: PayPalTelemetryEvent[];
  version: number;
}

// ---------------------------------------------------------------------------
// 8. Helper Functions
// ---------------------------------------------------------------------------

/**
 * Formats an integer minor amount (cents) to a standard USD currency string ($X.XX).
 * e.g., 20000 -> "$200.00"
 */
export function formatMinorToUSD(amountMinor: number): string {
  const dollars = (amountMinor / 100).toFixed(2);
  return `$${dollars}`;
}

/**
 * Parses a numeric dollar amount into integer minor units (cents).
 * Applies rounding to eliminate floating-point precision artifacts.
 * e.g., 200.00 -> 20000
 */
export function parseUSDToMinor(usd: number): number {
  return Math.round(usd * 100);
}
